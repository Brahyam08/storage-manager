#!/usr/bin/env python3
"""Exercise Docker/PostgreSQL with synthetic data in a disposable Compose project."""
import concurrent.futures
import json
import os
from pathlib import Path
import secrets
import subprocess
import tempfile
import time
import urllib.error
import urllib.request

ROOT = Path(__file__).resolve().parents[1]

LEGACY_SCHEMA = """
CREATE TABLE users (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username varchar(255) NOT NULL UNIQUE, email varchar(255) NOT NULL UNIQUE,
 password varchar(255) NOT NULL, role varchar(255) NOT NULL);
CREATE TABLE locations (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(255) NOT NULL, description varchar(255));
CREATE TABLE items (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(255) NOT NULL, description varchar(255), category varchar(255),
 quantity integer NOT NULL, location_id bigint NOT NULL REFERENCES locations(id));
CREATE TABLE item_movements (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_id bigint NOT NULL REFERENCES items(id), from_location_id bigint NOT NULL REFERENCES locations(id),
 to_location_id bigint NOT NULL REFERENCES locations(id), quantity integer NOT NULL, moved_at timestamp NOT NULL);
INSERT INTO users(username,email,password,role) VALUES ('legacy','legacy@example.invalid','unused-fixture','VIEWER');
INSERT INTO locations(name) VALUES ('Legacy source'), ('Legacy drawer');
INSERT INTO items(name,quantity,location_id) VALUES ('Legacy screws',10,2);
INSERT INTO item_movements(item_id,from_location_id,to_location_id,quantity,moved_at)
 VALUES (1,1,2,10,'2026-01-01 12:00:00');
"""


def check(condition, message):
    if not condition:
        raise AssertionError(message)


def verify():
    project = "storage-verify-" + secrets.token_hex(4)
    with tempfile.TemporaryDirectory(prefix="storage-docker-verify-") as temporary:
        environment_file = Path(temporary) / ".env"
        environment_file.write_text(
            "POSTGRES_DB=storage_verify\nPOSTGRES_USER=storage_verify\n"
            + "POSTGRES_PASSWORD=" + secrets.token_urlsafe(32) + "\n"
            + "JWT_SECRET=" + secrets.token_urlsafe(48) + "\nAPI_PORT=0\nDB_PORT=0\n")
        environment_file.chmod(0o600)
        # Explicit values prevent a developer's exported database credentials being used.
        environment = os.environ.copy()
        for line in environment_file.read_text().splitlines():
            key, value = line.split("=", 1)
            environment[key] = value
        compose = ["docker", "compose", "--project-name", project,
                   "--env-file", str(environment_file), "-f", str(ROOT / "docker-compose.yml")]

        def command(*arguments, capture=False, sql=None):
            result = subprocess.run(compose + list(arguments), cwd=ROOT, env=environment,
                                    input=sql, text=True, capture_output=capture, check=True)
            return result.stdout.strip() if capture else None

        def query(sql):
            return command("exec", "-T", "db", "psql", "-U", "storage_verify", "-d", "storage_verify",
                           "-v", "ON_ERROR_STOP=1", "-At", capture=True, sql=sql)

        def base_url():
            address = command("port", "app", "8080", capture=True).splitlines()[0]
            print("Checking API on " + address, flush=True)
            return "http://" + address

        url = ""

        def api(method, path, token=None, body=None, expected=200, extra_headers=None):
            headers = {"Content-Type": "application/json"}
            headers.update(extra_headers or {})
            if token:
                headers["Authorization"] = "Bearer " + token
            request = urllib.request.Request(url + path, method=method, headers=headers,
                    data=None if body is None else json.dumps(body).encode())
            try:
                with urllib.request.urlopen(request, timeout=30) as response:
                    status, payload = response.status, response.read()
            except urllib.error.HTTPError as error:
                status, payload = error.code, error.read()
            if expected is not None:
                check(status == expected, f"{method} {path}: expected {expected}, got {status}")
            return status, json.loads(payload) if payload else None

        def wait_for_api():
            deadline = time.monotonic() + 120
            last_error = "No response"
            while time.monotonic() < deadline:
                try:
                    api("GET", "/api/users/me", expected=401)
                    return
                except (OSError, AssertionError) as error:
                    last_error = str(error)
                    time.sleep(1)
            raise AssertionError("API did not become ready: " + last_error)

        def preserved_legacy_data():
            count = query("SELECT count(*) FROM items i JOIN locations l ON l.id=i.location_id "
                          "WHERE i.id=1 AND i.name='Legacy screws' AND i.quantity=10 "
                          "AND i.owner_id IS NULL AND i.visibility IS NULL AND l.house_id IS NULL;")
            check(count == "1", "Legacy inventory was lost or assigned automatically")
            check(query("SELECT count(*) FROM users WHERE id=1 AND username='legacy' "
                        "AND email='legacy@example.invalid' AND password='unused-fixture';") == "1",
                  "Legacy account was changed")
            check(query("SELECT count(*) FROM item_movements WHERE item_id=1 AND from_location_id=1 "
                        "AND to_location_id=2 AND quantity=10 AND moved_at='2026-01-01 12:00:00';") == "1",
                  "Legacy movement history was changed")

        try:
            print("Starting isolated PostgreSQL project: " + project, flush=True)
            command("up", "-d", "--wait", "db")
            query(LEGACY_SCHEMA)
            print("Synthetic legacy schema created; building and starting API", flush=True)
            command("up", "-d", "--build", "app")
            url = base_url()
            wait_for_api()
            preserved_legacy_data()
            _, schema = api("GET", "/v3/api-docs")
            check(schema["components"]["securitySchemes"]["bearerAuth"]["scheme"] == "bearer", "Missing Bearer scheme")
            check("/api/items/{id}/consume" in schema["paths"], "Consumption endpoint missing from OpenAPI")
            check(schema["paths"]["/api/auth/login"]["post"]["security"] == [], "Public login incorrectly documented")
            with urllib.request.urlopen(url + "/swagger-ui/index.html", timeout=30) as response:
                check(response.status == 200 and b"Swagger UI" in response.read(), "Swagger UI unavailable")
            print("OpenAPI schema, Bearer security and Swagger UI passed", flush=True)
            print("Schema update preserves legacy rows", flush=True)

            password = secrets.token_urlsafe(18)
            tokens = {}
            accounts = {}
            for name in ["owner", "member", "outsider"]:
                _, accounts[name] = api("POST", "/api/auth/register", body={"username": name,
                        "email": name + "@example.invalid", "password": password}, expected=201)
                _, login = api("POST", "/api/auth/login", body={"email": name + "@example.invalid", "password": password})
                tokens[name] = login["token"]
            api("POST", "/api/auth/register", body={}, expected=400)
            for duplicate in [{"username": "owner", "email": "new@example.invalid", "password": password},
                              {"username": "new", "email": " OWNER@EXAMPLE.INVALID ", "password": password}]:
                _, error = api("POST", "/api/auth/register", body=duplicate, expected=409)
                check(error == {"error": "No se puede registrar esa cuenta"}, "Duplicate registration exposed details")
            wrong = api("POST", "/api/auth/login", body={"email": "owner@example.invalid", "password": "wrong-password"}, expected=401)[1]
            missing = api("POST", "/api/auth/login", body={"email": "missing@example.invalid", "password": "wrong-password"}, expected=401)[1]
            check(wrong == missing == {"error": "Credenciales incorrectas"}, "Login errors reveal account existence")
            api("POST", "/api/auth/login", body={"email": "owner@example.invalid", "password": "é" * 36 + "a"}, expected=400)
            _, canonical_login = api("POST", "/api/auth/login", body={"email": " OWNER@EXAMPLE.INVALID ", "password": password})
            check(api("GET", "/api/users/me", canonical_login["token"])[1]["email"] == "owner@example.invalid", "Noncanonical login identity")
            with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
                registrations = list(pool.map(lambda _: api("POST", "/api/auth/register", body={
                    "username": "racer", "email": "racer@example.invalid", "password": password}, expected=None)[0], range(2)))
            check(sorted(registrations) == [201, 409], "Concurrent registration did not preserve uniqueness")
            check(query("SELECT count(*) FROM users WHERE username='racer';") == "1", "Duplicate account persisted")
            print("Authentication validation, generic errors and concurrent registration passed", flush=True)
            owner, member, outsider = (tokens[name] for name in ["owner", "member", "outsider"])
            _, house = api("POST", "/api/houses", owner, {"name": "Integration house"}, 201)
            _, invitation = api("POST", f"/api/houses/{house['id']}/invitation", owner)
            api("POST", "/api/houses/join", member, {"code": invitation["code"]})
            places = []
            for name in ["Drawer 1", "Drawer 2", "Drawer 3"]:
                _, place = api("POST", "/api/locations", owner, {"name": name, "houseId": house["id"]}, 201)
                places.append(place["id"])

            def create_item(name, quantity=10, visibility="PRIVATE"):
                return api("POST", "/api/items", owner, {"name": name, "quantity": quantity,
                    "locationId": places[0], "visibility": visibility}, 201)[1]["id"]

            private_id = create_item("Private screws")
            api("GET", f"/api/items/{private_id}", member, expected=404)
            api("GET", f"/api/items/{private_id}/consumptions", member, expected=404)
            api("GET", f"/api/items/{private_id}", outsider, expected=404)
            _, found = api("GET", "/api/items?search=Private", member)
            check(found == [], "Private item leaked through search")
            api("GET", "/api/items/1", owner, expected=404)
            shared_id = create_item("Shared screws", visibility="HOUSE_SHARED")
            _, stock = api("POST", f"/api/items/{shared_id}/consume", member, {"quantity": 5})
            check(stock["quantity"] == 5 and stock["location"]["id"] == places[0], "Incorrect consumption")
            api("POST", f"/api/items/{shared_id}/consume", member, {"quantity": 1.5}, expected=400)
            api("PATCH", f"/api/items/{shared_id}/move?toLocationId={places[1]}&quantity=5", member)
            with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
                results = list(pool.map(lambda _: api("POST", f"/api/items/{shared_id}/consume", member,
                                                {"quantity": 3}, expected=None)[0], range(2)))
            check(sorted(results) == [200, 409], "Concurrent consumption overspent or failed unexpectedly")
            _, stock = api("POST", f"/api/items/{shared_id}/consume", owner, {"quantity": 2})
            check(stock["quantity"] == 0 and stock["outOfStock"], "Zero-stock item not retained")
            _, consumption_history = api("GET", f"/api/items/{shared_id}/consumptions", member)
            check(len(consumption_history) == 3, "Consumption history missing")
            check(consumption_history[-1]["consumedById"] == accounts["member"]["id"], "Wrong session actor")
            api("GET", f"/api/items/{shared_id}/consumptions", outsider, expected=404)
            print("Privacy, shared stock, consumption and concurrent stock checks passed", flush=True)

            moving_id = create_item("Concurrent movement", quantity=2)
            with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
                results = list(pool.map(lambda place: api("PATCH",
                        f"/api/items/{moving_id}/move?toLocationId={place}&quantity=2", owner)[0], places[1:]))
            check(results == [200, 200], "Concurrent moves failed")
            _, history = api("GET", f"/api/items/{moving_id}/history", owner)
            check(len(history) == 2 and history[1]["fromLocation"]["id"] == places[0]
                  and history[0]["fromLocation"]["id"] == history[1]["toLocation"]["id"], "Broken movement chain")
            _, moved_item = api("GET", f"/api/items/{moving_id}", owner)
            check(moved_item["location"]["id"] == history[0]["toLocation"]["id"], "Location/history mismatch")
            print("Concurrent PostgreSQL movements preserve their history chain", flush=True)

            rollback_id = create_item("Rollback fixture", quantity=4)
            query("CREATE FUNCTION verification_reject_update() RETURNS trigger LANGUAGE plpgsql AS $$ "
                  f"BEGIN IF NEW.id = {rollback_id} THEN RAISE EXCEPTION 'verification failure'; END IF; RETURN NEW; END; $$; "
                  "CREATE TRIGGER verification_reject_update BEFORE UPDATE ON items "
                  "FOR EACH ROW EXECUTE FUNCTION verification_reject_update();")
            try:
                for method, path, body in [
                    ("POST", f"/api/items/{rollback_id}/consume", {"quantity": 1}),
                    ("PATCH", f"/api/items/{rollback_id}/move?toLocationId={places[1]}&quantity=4", None)]:
                    _, error = api(method, path, owner, body, expected=500)
                    check(error == {"error": "Error interno del servidor"}, "Forced database failure exposed internal details")
                _, saved = api("GET", f"/api/items/{rollback_id}", owner)
                check(saved["quantity"] == 4 and saved["location"]["id"] == places[0], "Failed transaction changed stock/location")
                check(api("GET", f"/api/items/{rollback_id}/consumptions", owner)[1] == [], "Consumption failed to roll back")
                check(api("GET", f"/api/items/{rollback_id}/history", owner)[1] == [], "Movement failed to roll back")
            finally:
                query("DROP TRIGGER verification_reject_update ON items; DROP FUNCTION verification_reject_update();")
            print("Forced PostgreSQL failures roll back stock, location and audit records", flush=True)

            for cycle in range(3):
                print("Removing containers and recreating them with the same test volume", flush=True)
                command("down")
                command("up", "-d", "--wait")
                url = base_url()
                wait_for_api()
                _, login = api("POST", "/api/auth/login", body={"email": "owner@example.invalid", "password": password})
                owner = login["token"]
                _, saved = api("GET", f"/api/items/{shared_id}", owner)
                check(saved["quantity"] == 0 and saved["location"]["id"] == places[1], "Inventory did not persist")
                check(api("GET", f"/api/items/{shared_id}/consumptions", owner)[1] == consumption_history, "Consumption history did not persist")
                check(api("GET", f"/api/items/{moving_id}/history", owner)[1] == history, "Movement history did not persist")
                api("GET", f"/api/houses/{house['id']}", member)
                preserved_legacy_data()
                print(f"Persistence/recreation cycle {cycle + 1}/3 passed", flush=True)
            # The last fresh instance has used one login and no registration attempts.
            for attempt in range(20):
                api("POST", "/api/auth/login", body={"email": "owner@example.invalid", "password": "wrong-password"},
                    expected=401 if attempt < 19 else 429)
            _, limited = api("POST", "/api/auth/login", body={"email": "another@example.invalid", "password": "wrong-password"},
                    expected=429, extra_headers={"X-Forwarded-For": "203.0.113.5", "Forwarded": "for=203.0.113.6"})
            check(limited == {"error": "Demasiados intentos. Inténtalo de nuevo más tarde"}, "Unexpected rate-limit error")
            api("GET", "/api/users/me", owner)
            for attempt in range(11):
                api("POST", "/api/auth/register", body={}, expected=400 if attempt < 10 else 429)
            print("Authentication quotas, spoofed forwarding headers and unaffected JWT access passed", flush=True)
            print("PASS: accounts, memberships, inventory and history survive container recreation", flush=True)
        except Exception:
            print(command("ps", "--all", "--format", "json", capture=True), flush=True)
            diagnostics = command("logs", "--no-color", "--tail", "100", "app", "db", capture=True)
            for key in ["POSTGRES_PASSWORD", "JWT_SECRET"]:
                diagnostics = diagnostics.replace(environment[key], "[redacted]")
            print(diagnostics, flush=True)
            raise
        finally:
            print("Cleaning only the isolated verification project's containers and volume", flush=True)
            command("down", "--volumes", "--remove-orphans")


if __name__ == "__main__":
    verify()
